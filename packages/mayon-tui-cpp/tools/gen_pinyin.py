#!/usr/bin/env python3
"""Regenerate ui/pinyin_table.inc from pypinyin (U+4E00..U+9FFF, first reading)."""
import sys
from pypinyin.constants import PINYIN_DICT
from pypinyin.style import convert

words = []
for code in range(0x4E00, 0xA000):
    entry = PINYIN_DICT.get(code, "")
    first = entry.split(",")[0] if entry else ""
    plain = convert(first, 0, True) if first else ""
    words.append("".join(c for c in plain.lower() if "a" <= c <= "z"))
text = " ".join(words)
with open(sys.argv[1], "w") as out:
    out.write("// Generated by tools/gen_pinyin.py from pypinyin; do not edit.\n")
    for start in range(0, len(text), 4000):
        out.write('"' + text[start : start + 4000] + '"\n')
