local M = {}

function M.setup()
	require("gitsigns").setup({})
	require("diffview").setup({})
	local function map(mode, lhs, callback, desc)
		vim.keymap.set(mode, lhs, callback, { desc = desc })
	end
	local gs = require("gitsigns")
	map("n", "]h", function()
		gs.nav_hunk("next")
	end, "Next git hunk")
	map("n", "[h", function()
		gs.nav_hunk("prev")
	end, "Prev git hunk")
	map("n", "<leader>gs", function()
		gs.stage_hunk()
	end, "Stage/unstage hunk")
	map("v", "<leader>gs", function()
		gs.stage_hunk({ vim.fn.line("."), vim.fn.line("v") })
	end, "Stage selection")
	map("n", "<leader>gr", function()
		gs.reset_hunk()
	end, "Reset hunk")
	map("v", "<leader>gr", function()
		gs.reset_hunk({ vim.fn.line("."), vim.fn.line("v") })
	end, "Reset selection")
	map("n", "<leader>gS", function()
		gs.stage_buffer()
	end, "Stage buffer")
	map("n", "<leader>gR", function()
		gs.reset_buffer()
	end, "Reset buffer")
	map("n", "<leader>gp", function()
		gs.preview_hunk_inline()
	end, "Preview hunk (inline)")
	map("n", "<leader>gb", function()
		gs.blame_line({ full = true })
	end, "Blame line")
	map("n", "<leader>gB", function()
		gs.toggle_current_line_blame()
	end, "Toggle line blame")
	map("n", "<leader>gd", function()
		gs.diffthis()
	end, "Diff against index")
	map("n", "<leader>gq", function()
		gs.setqflist("all")
	end, "All hunks to quickfix")
	vim.keymap.set("n", "<leader>gD", "<cmd>DiffviewOpen HEAD<cr>", { desc = "Diff against HEAD" })
	vim.keymap.set("n", "<leader>gH", "<cmd>DiffviewFileHistory %<cr>", { desc = "Current file history" })
	vim.keymap.set("n", "<leader>gC", "<cmd>DiffviewClose<cr>", { desc = "Close diff view" })
end

return M
